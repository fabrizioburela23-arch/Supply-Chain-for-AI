"""core/portfolio_advisor.py — COMITÉ DE CARTERA: analiza una cartera completa y
da ACCIONES CONCRETAS como consejo (reducir, vender, añadir, diversificar).

Pedido (2026-10-02, Fabrizio): "que el comité pueda analizar carteras, no solo
empresas, y que te dé acciones concretas, como quitar una posición o reducir
riesgo o adquirir otra posición, a modo de consejo, que advierta que es una IA,
pero que sí lo haga; quiero que una persona sin experiencia pueda usar esta app
y tener carteras de acuerdo a sus expectativas".

Cómo decide (todo AUDITABLE; la IA solo explica en lenguaje simple):
  1. RIESGO MEDIDO con precios reales (core/risk_report): peso, volatilidad,
     contribución al riesgo, correlaciones, máxima caída, VaR.
  2. PERFIL del inversionista (conservador / moderado / agresivo): topes por
     posición y por sector y volatilidad objetivo.
  3. INVESTIGACIÓN de los agentes (convicción por empresa, research/committee.board).
  4. REGLAS fijas → acciones: concentración, riesgo desproporcionado, convicción
     negativa, sector concentrado, volatilidad por encima del perfil, pares muy
     correlacionados, posiciones con convicción alta y poco peso, y candidatas
     para diversificar (de la Pizarra, en sectores que no tienes).
Cada acción trae: qué hacer, de cuánto a cuánto (% y USD), por qué (con la
cifra que lo justifica) y prioridad. Nada se ejecuta: aplicar en una cartera
simulada es un clic; en una cuenta real pasa por el bróker con tu PIN.
"""
