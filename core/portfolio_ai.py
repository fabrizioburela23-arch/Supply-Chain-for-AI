def _deterministic_answer(a, ids, caps, claims, pair, rows, rep, lang):
    en = lang == 'en'
    parts = _glossary(a['question'], lang)
    nodes_ = _nodes()
    g = _graph()
    for nid in ids[:3]:
        n = nodes_.get(nid) or {}
        deg = g['flow_deg'].get(nid, 0)
        live = caps.get(nid) or {}
        s = (f'{n.get("label")}: sector {sector_label(n.get("sector"), lang)}, NRS {nrs(n, deg)}/100, '
             f'{deg} {"supply-chain links" if en else "vínculos en la cadena"}')
        if live.get('price') is not None:
            s += f', {"price" if en else "precio"} ${live["price"]}'
        cl = claims.get(nid) or []
        if cl:
            s += (f'; {len(cl)} active agent claims' if en else f'; {len(cl)} claims activos de agentes')
        parts.append(s + '.')
    if pair:
        for p in pair['pairs'][:3]:
            lvl = ('high' if en else 'alta') if p['corr'] >= 0.6 else (('moderate' if en else 'moderada') if p['corr'] >= 0.3
                                                                     else ('low' if en else 'baja'))
            parts.append((f'{p["a"]} and {p["b"]}: daily correlation {p["corr"]} ({lvl}) over the last year.' if en else
                          f'{p["a"]} y {p["b"]}: correlación diaria {p["corr"]} ({lvl}) en el último año.'))
    if rep and rep.get('ok'):
        top = rep['positions'][0] if rep['positions'] else None
        parts.append((f'Your portfolio: annual volatility {rep["vol_ann_pct"]}%, 1-day VaR 95% ${rep["var95"]["hist_1d_usd"]}.'
                      if en else f'Tu cartera: volatilidad anual {rep["vol_ann_pct"]}%, VaR 95% a 1 día ${rep["var95"]["hist_1d_usd"]}.')
                     + ((f' {top["symbol"]} contributes {top["risk_contrib_pct"]}% of the risk.' if en else
                         f' {top["symbol"]} aporta el {top["risk_contrib_pct"]}% del riesgo.') if top else ''))
    if not parts:
        parts.append('I can explain concepts (diversify, volatility, VaR, NRS, correlation), compare companies of the '
                     'graph or analyze your selected portfolio. To get a portfolio built with real data, press '
                     '"Propose a portfolio".' if en else
                     'Puedo explicarte conceptos (diversificar, volatilidad, VaR, NRS, correlación), comparar empresas '
                     'del grafo o analizar tu cartera seleccionada. Para una cartera armada con datos reales, pulsa '
                     '"Proponme una cartera".')
    parts.append('(sin IA — respuesta automática con datos de Khipus; no es asesoría)' if not en else
                 '(no AI — automatic answer with Khipus data; not advice)')
    return '\n\n'.join(parts)


