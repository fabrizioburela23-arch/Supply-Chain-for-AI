# ── validación ───────────────────────────────────────────────────────────────
def _as_list(v, max_items, max_len):
    if v is None or v == '':
        return []
    if isinstance(v, str):
        v = [x for x in re.split(r'[,;\n]', v)]
    if not isinstance(v, list):
        raise ValidationError('formato de lista inválido', 'invalid list format')
    out = []
    for x in v:
        x = str(x or '').strip()[:max_len]
        if x and x not in out:
            out.append(x)
    if len(out) > max_items:
        raise ValidationError(f'máximo {max_items} elementos', f'at most {max_items} items')
    return out


def validate_propose(body):
    if not isinstance(body, dict):
        raise ValidationError('cuerpo JSON inválido', 'invalid JSON body')
    goal = GOALS.get(str(body.get('goal') or 'equilibrio').lower())
    horizon = HORIZONS.get(str(body.get('horizon') or '1-3').lower())
    risk = RISKS.get(str(body.get('risk') or 'medio').lower())
    if not goal:
        raise ValidationError('objetivo inválido (crecimiento/equilibrio/defensivo)',
                              'invalid goal (growth/balanced/defensive)')
    if not horizon:
        raise ValidationError('horizonte inválido (lt1, 1-3, 3+)', 'invalid horizon (lt1, 1-3, 3+)')
    if not risk:
        raise ValidationError('riesgo inválido (bajo/medio/alto)', 'invalid risk (low/medium/high)')
    try:
        amount = float(body.get('amount_usd'))
    except (TypeError, ValueError):
        raise ValidationError('monto inválido', 'invalid amount') from None
    if not math.isfinite(amount) or amount < 100 or amount > 10_000_000:
        raise ValidationError('el monto debe estar entre 100 y 10.000.000 USD',
                              'amount must be between 100 and 10,000,000 USD')
    themes = [t.lower() for t in _as_list(body.get('themes'), 11, 30)]
    unknown = [t for t in themes if t not in THEMES]
    if unknown:
        raise ValidationError('tema desconocido: ' + ', '.join(unknown), 'unknown theme: ' + ', '.join(unknown))
    exclude = _as_list(body.get('exclude'), 20, 60)
    return {'goal': goal, 'horizon': horizon, 'risk': risk, 'amount_usd': round(amount, 2),
            'themes': themes, 'exclude': exclude, 'lang': _lang(body.get('lang'))}


