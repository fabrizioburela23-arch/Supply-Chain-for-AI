def deterministic_rationale(pf, p, lang):
    en = lang == 'en'
    m = pf['metrics']
    names = ', '.join(f'{x["label"]} {round(x["weight"] * 100, 1)}%' for x in pf['positions'][:5])
    themes = ', '.join(theme_label(t, lang) for t in p['themes']) or ('all sectors of the graph' if en else 'todos los sectores del grafo')
    how = ('inverse volatility: the steadier names weigh more' if en else
           'inversa de la volatilidad: las más estables pesan más') if pf['method'] == 'inverse_vol' else \
          ('risk parity: each name contributes a similar share of risk' if en else
           'paridad de riesgo: cada empresa aporta un riesgo parecido')
    why = {
        'diversificada': ('the best ranked by risk score (NRS), size and role in the supply chain, spread across sectors'
                          if en else 'las mejor puntuadas por riesgo (NRS), tamaño y papel en la cadena, repartidas entre sectores'),
        'baja_vol': ('the calmest stocks of the last year among the well-ranked ones' if en else
                     'las acciones más tranquilas del último año entre las bien puntuadas'),
        'conviccion': ('the most connected companies of the supply chain (key suppliers/customers)' if en else
                       'las empresas más conectadas de la cadena de suministro (proveedores/clientes clave)'),
    }.get(pf['id'], '')
    var = f'${m["var95_1d_usd"]:,.2f}'
    if en:
        return (f'Theme: {themes}. We chose {m["n_names"]} listed companies: {why}. Main weights: {names}. '
                f'Sizing by {how}. Estimated annual volatility {m["vol_ann_pct"]}%; on a bad day (1 in 20) '
                f'the loss could exceed {var}. What would change the view: if correlations rise, if the NRS of a '
                f'large name worsens, or if research agents publish negative claims.')
    return (f'Tema: {themes}. Elegimos {m["n_names"]} empresas cotizadas: {why}. Pesos principales: {names}. '
            f'Tamaño por {how}. Volatilidad anual estimada {m["vol_ann_pct"]}%; en un mal día (1 de cada 20) '
            f'la pérdida podría superar {var}. Qué cambiaría la vista: si las correlaciones suben, si empeora el '
            f'NRS de un nombre grande o si los agentes publican claims negativos.')


def _ai_rationales(pfs, p, lang):
    """Una sola llamada para todas las carteras → {id: texto} o {} si no hay IA."""
    from core import ai as _ai
    if not _ai._ai_configured():
        return {}, None
    data = []
    for pf in pfs:
        m = pf['metrics']
        data.append({'id': pf['id'], 'nombre': pf['name'], 'metodo': pf['method'],
                     'posiciones': [{'empresa': x['label'], 'ticker': x['symbol'], 'sector': x['sector_label'],
                                     'pais': x['country'], 'peso_pct': round(x['weight'] * 100, 1),
                                     'usd': x['usd'], 'vol_anual_pct': x['vol_ann_pct'], 'nrs': x['nrs'],
                                     'aporte_riesgo_pct': x['risk_contrib_pct']} for x in pf['positions']],
                     'vol_anual_pct': m['vol_ann_pct'], 'var95_1dia_usd': m['var95_1d_usd'],
                     'caida_maxima_pct': m['max_drawdown_pct'], 'ratio_diversificacion': m['diversification_ratio'],
                     'correlacion_media': m['avg_correlation'], 'beta_sp500': m['beta_spy'],
                     'riesgos': pf['risks']})
    system = ('Eres el asistente educativo de carteras de Khipus Finance AI. Explicas a inversionistas NO expertos, '
              'en lenguaje simple y sin jerga, por qué una cartera ya construida tiene esas empresas y pesos. '
              'Usa SOLO los datos dados (no inventes cifras, precios ni rendimientos). Nunca prometas ganancias ni '
              'digas "compra"/"vende": es una propuesta educativa. Responde en ' +
              ('inglés' if lang == 'en' else 'español') + '.')
    prompt = (f'Perfil del usuario: objetivo {p["goal"]}, horizonte {p["horizon"]} años, riesgo {p["risk"]}, '
              f'monto ${p["amount_usd"]:,.2f} USD, temas {p["themes"] or "todos"}.\n'
              f'Carteras (JSON):\n{json.dumps(data, ensure_ascii=False)}\n\n'
              'Devuelve SOLO un JSON: {"<id>": "<3-5 frases: por qué estas empresas y pesos, los riesgos principales '
              'y qué cambiaría la vista>"} con una entrada por cartera.')
    try:
        text, used = _ai._ai_complete(system, prompt, max_tokens=1400, tier='fast')
        obj = _ai._extract_json(text)
        if isinstance(obj, dict):
            return {k: str(v)[:1500] for k, v in obj.items() if isinstance(v, str) and v.strip()}, used
    except Exception as e:  # noqa: BLE001
        log.warning('portfolio_ai: redacción IA falló (%s)', str(e)[:120])
    return {}, None


def propose(p, history_fn=None, fx_fn=None, caps=None, claims=None, use_ai=True):
    res = build_proposals(p, history_fn=history_fn, fx_fn=fx_fn, caps=caps, claims=claims)
    lang = p['lang']
    if not res.get('ok'):
        return res
    texts, model = (_ai_rationales(res['portfolios'], p, lang) if use_ai else ({}, None))
    for pf in res['portfolios']:
        det = deterministic_rationale(pf, p, lang)
        if texts.get(pf['id']):
            pf['rationale'], pf['rationale_source'], pf['model'] = texts[pf['id']], 'ai', model
        else:
            pf['rationale'], pf['rationale_source'] = det, 'sin IA'
        pf['rationale_deterministic'] = det
    res['disclaimer'] = DISCLAIMER[lang]
    res['disclaimer_es'], res['disclaimer_en'] = DISCLAIMER['es'], DISCLAIMER['en']
    res['as_of'] = _now()
    res['request'] = p
    return res


