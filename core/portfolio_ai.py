def validate_ask(body):
    if not isinstance(body, dict):
        raise ValidationError('cuerpo JSON inválido', 'invalid JSON body')
    q = str(body.get('question') or '').strip()
    if len(q) < 2:
        raise ValidationError('escribe una pregunta', 'write a question')
    if len(q) > 800:
        raise ValidationError('pregunta demasiado larga (máx. 800)', 'question too long (max 800)')
    hist = body.get('history') or []
    if not isinstance(hist, list):
        raise ValidationError('historial inválido', 'invalid history')
    history = []
    for h in hist[-6:]:
        if isinstance(h, dict) and h.get('text'):
            history.append({'role': 'user' if h.get('role') == 'user' else 'assistant',
                            'text': str(h['text'])[:600]})
    positions = []
    pf = body.get('portfolio')
    if pf is not None:
        if not isinstance(pf, dict) or not isinstance(pf.get('positions', []), list):
            raise ValidationError('cartera inválida', 'invalid portfolio')
        if len(pf.get('positions') or []) > 30:
            raise ValidationError('máximo 30 posiciones', 'at most 30 positions')
        for x in pf.get('positions') or []:
            if not isinstance(x, dict):
                continue
            try:
                sh = float(x.get('shares')) if x.get('shares') is not None else None
                usd = float(x.get('usd')) if x.get('usd') is not None else None
            except (TypeError, ValueError):
                raise ValidationError('cantidad inválida en la cartera', 'invalid amount in portfolio') from None
            positions.append({'node_id': str(x.get('node_id') or '')[:120], 'symbol': str(x.get('symbol') or '')[:15],
                              'label': str(x.get('label') or '')[:80], 'shares': sh, 'usd': usd})
    return {'question': q, 'history': history, 'positions': positions, 'lang': _lang(body.get('lang')),
            'portfolio_name': str((pf or {}).get('name') or '')[:80]}


