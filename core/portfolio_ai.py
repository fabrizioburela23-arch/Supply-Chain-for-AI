def _std(x):
    if len(x) < 2:
        return 0.0
    m = sum(x) / len(x)
    return math.sqrt(sum((v - m) ** 2 for v in x) / (len(x) - 1))


def _cov(a, b):
    n = len(a)
    if n < 2:
        return 0.0
    ma, mb = sum(a) / n, sum(b) / n
    return sum((x - ma) * (y - mb) for x, y in zip(a, b)) / (n - 1)


def common_returns(histories, syms):
    """(fechas comunes, {sym: retornos diarios}) sobre los días comunes."""
    common = sorted(set.intersection(*(set(histories[s]) for s in syms))) if syms else []
    rets = {s: [histories[s][common[i]] / histories[s][common[i - 1]] - 1.0 for i in range(1, len(common))]
            for s in syms}
    return common, rets


def inverse_vol(vols):
    inv = {s: 1.0 / v for s, v in vols.items() if v and v > 0}
    tot = sum(inv.values())
    return {s: x / tot for s, x in inv.items()} if tot else {}


def risk_parity(cov, syms, iters=600):
    """Contribución al riesgo IGUAL por nombre (ERC), iteración multiplicativa."""
    w = inverse_vol({s: math.sqrt(cov[s][s]) for s in syms})
    if not w:
        return {}
    n = len(syms)
    for _ in range(iters):
        sw = {a: sum(cov[a][b] * w[b] for b in syms) for a in syms}
        pv = sum(w[a] * sw[a] for a in syms)
        if pv <= 0:
            break
        target = pv / n
        new = {a: w[a] * math.sqrt(target / (w[a] * sw[a])) if w[a] * sw[a] > 0 else w[a] for a in syms}
        tot = sum(new.values())
        new = {a: v / tot for a, v in new.items()}
        if max(abs(new[a] - w[a]) for a in syms) < 1e-10:
            w = new
            break
        w = new
    return w


def _waterfill(w, cap):
    w = dict(w)
    for _ in range(len(w) + 2):
        over = {s for s, v in w.items() if v > cap + 1e-12}
        if not over:
            break
        excess = sum(w[s] - cap for s in over)
        for s in over:
            w[s] = cap
        free = [s for s in w if w[s] < cap - 1e-12]
        base = sum(w[s] for s in free)
        if not free or base <= 0:
            break
        for s in free:
            w[s] += excess * w[s] / base
    return w


def apply_caps(w, meta, max_name, max_sector, max_country):
    """Topes por nombre, sector y país redistribuyendo el exceso de forma
    proporcional. Un tope de grupo imposible (p.ej. un solo sector elegido) se
    RELAJA y se informa. Devuelve (pesos normalizados, relajados[])."""
    w = dict(w)
    tot = sum(w.values())
    if tot <= 0:
        return w, []
    w = {s: v / tot for s, v in w.items()}
    relaxed = []
    max_name = max(max_name, 1.0 / len(w))
    for key, cap in (('sector', max_sector), ('country', max_country)):
        # factible solo si los grupos, llenos hasta su tope (y el de nombre), suman ≥ 100 %
        sizes = defaultdict(int)
        for s in w:
            sizes[meta[s][key]] += 1
        if sum(min(cap, k * max_name) for k in sizes.values()) < 1 - 1e-9:
            relaxed.append(key)
    for _ in range(200):
        w = _waterfill(w, max_name)
        moved = False
        for key, cap in (('sector', max_sector), ('country', max_country)):
            if key in relaxed:
                continue
            groups = defaultdict(list)
            for s in w:
                groups[meta[s][key]].append(s)
            gt = {g: sum(w[s] for s in m) for g, m in groups.items()}
            over = {g for g, t in gt.items() if t > cap + 1e-9}
            if not over:
                continue
            excess = sum(gt[g] - cap for g in over)
            for g in over:
                for s in groups[g]:
                    w[s] *= cap / gt[g]
            under = [s for s in w if meta[s][key] not in over and w[s] < max_name - 1e-12]
            base = sum(w[s] for s in under)
            if not under or base <= 0:
                continue
            for s in under:
                w[s] += excess * w[s] / base
            moved = True
        if not moved and max(w.values()) <= max_name + 1e-9:
            break
    tot = sum(w.values())
    w = _waterfill({s: v / tot for s, v in w.items()}, max_name)   # el tope por nombre manda
    for key, cap in (('sector', max_sector), ('country', max_country)):
        gt = defaultdict(float)
        for s, v in w.items():
            gt[meta[s][key]] += v
        if key not in relaxed and max(gt.values()) > cap + 1e-4:
            relaxed.append(key)       # topes combinados incompatibles → se informa
    return w, relaxed


def score(c, prof_w, goal, max_deg, research):
    q = 1 - c['nrs'] / 100.0
    cent = math.sqrt(c['degree'] / max_deg) if max_deg else 0.0
    mcap = c.get('mcap_b')
    size = max(0.0, min(1.0, math.log10(mcap) / math.log10(3000))) if mcap and mcap > 1 else (0.3 if mcap is None else 0.0)
    res = (research.get(c['id']) or {}).get('net', 0.0)
    wq, wc = prof_w['q'], prof_w['cent']
    if goal == 'defensivo':
        wq += 0.10
    elif goal == 'crecimiento':
        wc += 0.10
    return round(wq * q + prof_w['size'] * size + wc * cent + prof_w['res'] * res +
                 prof_w['live'] * (1.0 if c.get('live') else 0.0), 6)


def research_signal(claims):
    """{id: {net ∈ [-1,1], n, neg}} desde claims activos (confianza como peso)."""
    out = {}
    for nid, cl in (claims or {}).items():
        num = den = 0.0
        neg = 0
        for c in cl:
            s = {'positive': 1, 'negative': -1}.get(c.get('stance'), 0)
            num += s * c.get('confidence', 0)
            den += c.get('confidence', 0)
            neg += 1 if s < 0 else 0
        out[nid] = {'net': round(num / den, 3) if den else 0.0, 'n': len(cl), 'neg': neg}
    return out


