def _pair_stats(ids, history_fn=None):
    """Correlación y volatilidad reales (1 año) entre 2-4 cotizadas mencionadas."""
    history_fn = history_fn or _history
    nodes_ = _nodes()
    syms = {}
    for nid in ids:
        s = _safe_ticker((nodes_.get(nid, {}).get('mkt') or '').strip().upper())
        if s:
            syms[s] = nodes_[nid].get('label') or nid
    if len(syms) < 2:
        return None
    futs = {s: _POOL.submit(history_fn, s) for s in list(syms)[:4]}
    wait(list(futs.values()), timeout=15)
    hist = {}
    for s, f in futs.items():
        try:
            h, _cur = f.result(timeout=0) if f.done() else ({}, None)
        except Exception:  # noqa: BLE001
            h = {}
        if len(h or {}) >= MIN_DAYS:
            hist[s] = h
    if len(hist) < 2:
        return None
    ss = sorted(hist)
    common, rets = common_returns(hist, ss)
    if len(common) < MIN_DAYS:
        return None
    vol = {s: round(_std(rets[s]) * math.sqrt(252) * 100, 1) for s in ss}
    pairs = []
    for i, a in enumerate(ss):
        for b in ss[i + 1:]:
            sa, sb = _std(rets[a]), _std(rets[b])
            if sa and sb:
                pairs.append({'a': syms[a], 'b': syms[b], 'corr': round(_cov(rets[a], rets[b]) / (sa * sb), 2)})
    return {'vol': {syms[s]: v for s, v in vol.items()}, 'pairs': pairs, 'days': len(common) - 1,
            'from': common[0], 'to': common[-1]}


def _portfolio_ctx(positions, caps):
    """Composición + reporte de riesgo real de la cartera enviada (caché 30 min)."""
    from core.entities import resolve
    nodes_ = _nodes()
    rows, calc, skipped = [], [], []
    for x in positions:
        nid = x['node_id'] if x['node_id'] in nodes_ else ((resolve(x['symbol'] or x['label'], 85) or {}).get('id'))
        n = nodes_.get(nid) or {}
        sym = _safe_ticker((x['symbol'] or n.get('mkt') or '').strip().upper())
        label = n.get('label') or x['label'] or sym or '?'
        sh = x['shares']
        if (sh is None or sh <= 0) and x['usd'] and nid and (caps.get(nid) or {}).get('price'):
            sh = x['usd'] / caps[nid]['price']
        rows.append({'label': label, 'symbol': sym, 'node_id': nid, 'sector': n.get('sector'),
                     'country': n.get('country'), 'shares': sh})
        if sym and sh and sh > 0:
            calc.append({'symbol': sym, 'shares': sh, 'label': label})
        else:
            skipped.append(label)
    rep = None
    if calc:
        k = _key('pfrep', sorted((c['symbol'], round(c['shares'], 4)) for c in calc))
        rep = _cache_get(k, 1800)
        if rep is None:
            try:
                rep = _portfolio_report(calc)
            except Exception as e:  # noqa: BLE001
                rep = {'ok': False, 'error': type(e).__name__}
            _cache_put(k, rep)
    return rows, rep, skipped


def _portfolio_text(rows, rep, skipped, lang):
    lines = ['CARTERA SELECCIONADA DEL USUARIO (simulada):']
    for r in rows:
        lines.append(f'- {r["label"]} ({r["symbol"] or "no cotiza"}; sector {sector_label(r["sector"], lang) if r["sector"] else "?"}; '
                     f'país {r["country"] or "?"})')
    if rep and rep.get('ok'):
        lines.append(f'Riesgo real (1 año, {rep["days"]} días hasta {rep["as_of"]}): valor {rep["portfolio_value_usd"]} USD; '
                     f'volatilidad anual {rep["vol_ann_pct"]}%; VaR 95% 1 día {rep["var95"]["hist_1d_usd"]} USD '
                     f'({rep["var95"]["hist_1d_pct"]}%); caída máxima {rep["max_drawdown_pct"]}%; '
                     f'beta vs S&P 500 {rep["beta_spy"]}; ratio de diversificación {rep["diversification_ratio"]}.')
        for p in rep['positions'][:8]:
            lines.append(f'  · {p["symbol"]}: peso {p["weight_pct"]}%, vol anual {p["vol_ann_pct"]}%, '
                         f'aporte al riesgo {p["risk_contrib_pct"]}%')
    elif rep:
        lines.append(f'(No se pudo medir el riesgo: {rep.get("error")})')
    if skipped:
        lines.append('Sin cotización (fuera del cálculo): ' + ', '.join(skipped[:8]))
    return '\n'.join(lines)


def _mentioned(question, history):
    from core.entities import resolve
    from core.live_facts import detect_entities
    ids = detect_entities(question, limit=5)
    if not ids:        # "nvidia", "amd" en minúsculas: tokens sueltos por el resolutor
        for tok in re.findall(r'[A-Za-zÀ-ÿ0-9.&-]{3,}', question)[:25]:
            r = resolve(tok, 90)
            if r and r['id'] not in ids:
                ids.append(r['id'])
            if len(ids) >= 5:
                break
    return ids


def _glossary(question, lang):
    ql = question.lower()
    return [(en if lang == 'en' else es) for rx, es, en in GLOSSARY if re.search(rx, ql)]


def ask(a, history_fn=None, caps=None, claims=None):
    lang = a['lang']
    caps = caps if caps is not None else (_live_caps().get('caps') or {})
    ids = _mentioned(a['question'], a['history'])
